// Verification-prep: recompiles the exact compiler input used for the artifacts and emits
// everything needed to verify RareCognos + RareCognosMarket on the LiteForge explorer:
//   artifacts/verification/standard-json-input.json  — solc standard JSON input (upload as-is)
//   artifacts/verification/verification-meta.json    — compiler version, settings, bytecode hashes
//   artifacts/verification/README.md                 — exact verification steps (UI / API / Sourcify)
// Keyless and network-free. Pass --collection 0x.. (after deploy) to embed encoded constructor args.
import fs from "node:fs";
import solc from "solc";
import { keccak256, encodeAbiParameters, isAddress } from "viem";

if (!fs.existsSync("artifacts/compiler-input.json")) {
  console.error('artifacts/compiler-input.json missing — run "npm run nft:compile" first');
  process.exit(1);
}

const collectionArgIdx = process.argv.indexOf("--collection");
const collectionArg = collectionArgIdx >= 0 ? process.argv[collectionArgIdx + 1] : undefined;
const treasuryArgIdx = process.argv.indexOf("--treasury");
const treasuryArg = treasuryArgIdx >= 0 ? process.argv[treasuryArgIdx + 1] : undefined;
if (collectionArg !== undefined && !isAddress(collectionArg)) {
  console.error(`--collection ${collectionArg} is not a valid address`);
  process.exit(1);
}
if ((collectionArgIdx >= 0 && !collectionArg) || (treasuryArgIdx >= 0 && !treasuryArg) ||
    (treasuryArg !== undefined && (!isAddress(treasuryArg) || /^0x0{40}$/i.test(treasuryArg))) ||
    (!!collectionArg !== !!treasuryArg)) {
  console.error("Provide both --collection and nonzero --treasury, or neither.");
  process.exit(1);
}

const input = JSON.parse(fs.readFileSync("artifacts/compiler-input.json", "utf8"));
const out = JSON.parse(
  solc.compile(JSON.stringify(input), {
    import: (p) => ({ contents: fs.readFileSync("node_modules/" + p, "utf8") }),
  }),
);
if (out.errors?.some((e) => e.severity === "error"))
  throw Error(JSON.stringify(out.errors).slice(0, 400));
const version = solc.version();

fs.mkdirSync("artifacts/verification", { recursive: true });
fs.writeFileSync("artifacts/verification/standard-json-input.json", JSON.stringify(input, null, 2));

let marketArgsHex;
if (collectionArg && treasuryArg) marketArgsHex = encodeAbiParameters([{ type: "address" }, { type: "address" }], [collectionArg, treasuryArg]);

const meta = {
  generatedAt: new Date().toISOString(),
  solcVersion: version,
  evmVersion: input.settings.evmVersion,
  optimizer: input.settings.optimizer,
  license: "MIT",
  sourceFile: "RareCognos.sol",
  collectionAddress: collectionArg || null,
  treasuryAddress: treasuryArg || null,
  contracts: {},
};
for (const [name, c] of Object.entries(out.contracts["RareCognos.sol"])) {
  const runtime = "0x" + c.evm.deployedBytecode.object;
  const creation = "0x" + c.evm.bytecode.object;
  meta.contracts[name] = {
    constructorArgs: name === "RareCognos" ? [] : [collectionArg || "<deployed RareCognos address>", treasuryArg || "<treasury address>"],
    constructorArgsHex:
      name === "RareCognos" ? null : marketArgsHex || "<run with --collection 0x.. --treasury 0x.. after deploy>",
    deployedBytecodeKeccak256: keccak256(runtime),
    creationBytecodeKeccak256: keccak256(creation),
    deployedBytecodeBytes: (runtime.length - 2) / 2,
    immutableReferences: c.evm.deployedBytecode.immutableReferences,
  };
}
fs.writeFileSync("artifacts/verification/verification-meta.json", JSON.stringify(meta, null, 2));

const nft = meta.contracts.RareCognos;
const market = meta.contracts.RareCognosMarket;
const readme = `# LiteForge testnet contract verification — prepared inputs

Generated by \`scripts/nft-verify-prep.mjs\` on ${meta.generatedAt}. Keyless — these files only
prepare the inputs; the actual verification happens on the explorer (manual, or CI later).

| Setting | Value |
| --- | --- |
| Compiler | solc **${version}** |
| EVM version | **${meta.evmVersion}** |
| Optimizer | ${meta.optimizer.enabled ? `enabled, ${meta.optimizer.runs} runs` : "disabled"} |
| License | ${meta.license} |
| Source file | \`contracts/${meta.sourceFile}\` (contains **both** contracts) |
| Collection address | ${meta.collectionAddress || "_not deployed yet — rerun with --collection 0x.. after deploy_"} |

## Bytecode fingerprints (compare against the explorer after deployment)

| Contract | runtime keccak256 | bytes | constructor args |
| --- | --- | --- | --- |
| RareCognos | \`${nft.deployedBytecodeKeccak256}\` | ${nft.deployedBytecodeBytes} | none |
| RareCognosMarket | \`${market.deployedBytecodeKeccak256}\` | ${market.deployedBytecodeBytes} | collection and treasury addresses${marketArgsHex ? ` — encoded: \`${marketArgsHex}\`` : " (encode with --collection and --treasury)"} |

Runtime fingerprints above are compiler templates: immutable references are patched by the constructor,
so deployed runtime hashes must be compared after applying the deployed immutable values, not directly.

## Path A — LiteForge explorer UI (Blockscout-style)

1. Open https://explorer.testnet.liteforge.zeeve.net and search the deployed address.
2. Contract tab → **Verify & Publish** (Smart Contract verification).
3. Choose **Solidity (Standard JSON input)** and upload
   \`artifacts/verification/standard-json-input.json\`.
4. Compiler: **${version}** · EVM: **${meta.evmVersion}** · Optimization: **Yes (${meta.optimizer.runs} runs)** · License MIT.
5. Constructor arguments:
   - \`RareCognos\`: none.
   - \`RareCognosMarket\`: deployed collection address and treasury address${marketArgsHex ? ` (ABI-encoded: \`${marketArgsHex}\`)` : ""}.
6. Submit and wait for the verified badge. Record the two URLs into
   \`config/liteforge.json\` → \`verificationUrls\`, then set \`verified: true\`.

## Path B — Etherscan-style API (if the explorer exposes \`/api\`)

POST https://explorer.testnet.liteforge.zeeve.net/api with
\`module=contract&action=verifysource&codeformat=standard-json-input\` and the standard JSON
contents plus the settings above. Note: explorer API behavior to confirm post-migration.

## Path C — Sourcify (fallback)

If the explorer delegates to Sourcify: upload \`standard-json-input.json\` at
https://sourcify.dev/#/verify, chain 4441, same compiler settings, then link the returned
verification URL in \`config/liteforge.json\`.

## Post-verification checklist

1. Verify explorer source and compare deployed runtime after accounting for immutable values.
2. \`config/liteforge.json\`: \`verified: true\`, \`verificationUrls: [...]\`.
3. \`npm run testnet:acceptance -- --collection <addr> --market <addr>\` — state dump passes.
4. The app gate (\`configured\` in \`src/lib/nft/config.ts\`) now passes with auth-off defaults.
`;
fs.writeFileSync("artifacts/verification/README.md", readme);

console.log(`verify-prep: solc ${version} (${meta.evmVersion}, optimizer ${meta.optimizer.runs})`);
console.log(
  `wrote artifacts/verification/{standard-json-input.json, verification-meta.json, README.md}`,
);
console.log(
  `RareCognos runtime ${nft.deployedBytecodeBytes} B, market ${market.deployedBytecodeBytes} B`,
);
